// Generates src/upstream/reicons.ts from upstream's
// resources/views/components/reicon.blade.php (the `$icons` array).
// usage: node scripts/gen-reicons.mjs <path/to/reicon.blade.php> [upstream commit]
import fs from 'node:fs';

const [, , src, commit = 'unknown'] = process.argv;
const php = fs.readFileSync(src, 'utf8');
const body = php.slice(php.indexOf('$icons = ['), php.indexOf('];', php.indexOf('$icons = [')));
const icons = {};
// Entries look like:  'name' => '<path .../>',  (single-quoted, no escaped quotes inside)
for (const m of body.matchAll(/^\s*'([a-z0-9-]+)'\s*=>\s*'((?:[^'\\]|\\.)*)',?\s*$/gm)) {
  icons[m[1]] = m[2].replace(/\\'/g, "'");
}
const names = Object.keys(icons);
if (names.length === 0) throw new Error('no icons parsed');
const out =
  `// Generated by scripts/gen-reicons.mjs from upstream ${commit}\n` +
  `// resources/views/components/reicon.blade.php (Apache-2.0). Do not edit.\n\n` +
  `export const reicons: Record<string, string> = ${JSON.stringify(icons, null, 2)};\n`;
fs.writeFileSync(new URL('../src/upstream/reicons.ts', import.meta.url), out);
console.log(`wrote ${names.length} icons`);
